// Bundles the renderer (Monaco + app) into dist/ with esbuild.
import * as esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDevLauncher } from './dev-launcher.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const r = (...p) => path.join(root, ...p);
const watch = process.argv.includes('--watch');
buildDevLauncher(root);

// 1) Generate Monaco contribution imports from editor.main.js, minus the bundled
//    TS/CSS/HTML/JSON language services and the built-in lsp client (we ship our own).
const monacoEsm = r('node_modules/monaco-editor/esm/vs');
const editorMain = fs.readFileSync(path.join(monacoEsm, 'editor/editor.main.js'), 'utf8');
const contribs = editorMain
  .split(/\r?\n/)
  .filter((l) => /^import '\.\.?\//.test(l) && !l.includes('languages/') && !l.includes('external/'))
  .map((l) => {
    const rel = l.match(/'(.+)'/)[1];
    const abs = path.posix.join('../../../node_modules/monaco-editor/esm/vs/editor', rel);
    return `import '${abs}';`;
  });
const languages = ['csharp', 'cpp', 'xml', 'yaml', 'markdown', 'shell', 'powershell', 'ini', 'python', 'javascript', 'typescript', 'html', 'css', 'bat', 'lua'];
for (const l of languages) contribs.push(`import '../../../node_modules/monaco-editor/esm/vs/languages/definitions/${l}/register.js';`);
fs.mkdirSync(r('src/renderer/generated'), { recursive: true });
fs.writeFileSync(r('src/renderer/generated/monaco-contribs.js'), '// generated by scripts/build.mjs\n' + contribs.join('\n') + '\n');

fs.mkdirSync(r('dist'), { recursive: true });
fs.copyFileSync(r('src/renderer/index.html'), r('dist/index.html'));

const common = {
  bundle: true,
  minify: !watch,
  sourcemap: watch ? 'inline' : false,
  target: 'chrome130',
  logLevel: 'info',
  loader: { '.ttf': 'file', '.woff': 'file', '.woff2': 'file', '.svg': 'dataurl', '.png': 'file' },
};

const builds = [
  { ...common, entryPoints: { app: r('src/renderer/app.js') }, outdir: r('dist'), format: 'iife' },
  { ...common, entryPoints: { 'editor.worker': r('node_modules/monaco-editor/esm/vs/editor/editor.worker.js') }, outdir: r('dist'), format: 'iife' },
];

if (watch) {
  for (const b of builds) (await esbuild.context(b)).watch();
} else {
  await Promise.all(builds.map((b) => esbuild.build(b)));
  // Keep the license notices in sync with what ships (no-op when nothing changed).
  const { writeNotices } = await import('./notices.mjs');
  const { count } = writeNotices();
  console.log(`  THIRD_PARTY_NOTICES.txt  ${count} packages`);
}
